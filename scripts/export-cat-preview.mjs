import {readFile,writeFile} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const read=file=>readFile(resolve(root,'public',file),'utf8');
const files=['cat-memes.html','cat-memes.css','cat-meme-model.js','cat-meme-questions.js','cat-memes.js'];
const [html,css,model,questions,app]=await Promise.all(files.map(read));
const {catMemeQuestions,createCatMemeDeck}=await import('../public/cat-meme-questions.js');
const {packDeck}=await import('../public/cat-meme-model.js');
const assets={};
const mime=ext=>ext==='mp4'?'video/mp4':ext==='mp3'?'audio/mpeg':ext==='png'?'image/png':ext==='gif'?'image/gif':'image/jpeg';
const deck=await createCatMemeDeck(async(id,ext)=>{const data=await readFile(resolve(root,'public/cat-meme-assets',id+'.'+ext));assets[id+'.'+ext]='data:'+mime(ext)+';base64,'+data.toString('base64');return new Blob([data],{type:mime(ext)})});
let code=app.replace(/^import[^\n]*\n/gm,'');
const start=code.indexOf('async function starterDeck(){'),end=code.indexOf('async function addStarterDeck()',start);
if(start<0||end<0)throw Error('Starter loader not found');
code=code.slice(0,start)+`async function starterDeck(){return createCatMemeDeck(async(id,ext)=>{const response=await fetch(embeddedCatAssets[id+'.'+ext]);return response.blob()})}\n`+code.slice(end);
const strip=text=>text.replace(/^export /gm,'');
const script='const embeddedCatAssets='+JSON.stringify(assets)+';\n'+strip(model)+'\n'+strip(questions)+'\n'+code;
const result=html.replace('<link rel="stylesheet" href="/cat-memes.css">','<style>'+css+'</style>').replace('<script type="module" src="/cat-memes.js"></script>','<script type="module">\n'+script+'\n</script>').replace('href="/wedding_1212.html"','href="https://yutong-huaichu-wedding1212.pages.dev/"');
const target=resolve(process.argv[2]||resolve(root,'cat-memes-13-preview.html'));
await writeFile(target,result);
if(process.argv[3])await writeFile(resolve(process.argv[3]),JSON.stringify(await packDeck(deck,async blob=>Buffer.from(await blob.arrayBuffer()).toString('base64'))));
console.log(JSON.stringify({questions:catMemeQuestions.length,assets:Object.keys(assets).length,target,bytes:Buffer.byteLength(result)}));
